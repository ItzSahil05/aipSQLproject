CREATE TABLE IF NOT EXISTS WORKSHOPS (
    WORKSHOP_ID BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
    DEPARTMENT VARCHAR(100) NOT NULL,
    TITLE VARCHAR(200) NOT NULL,
    DESCRIPTION VARCHAR(1000),
    TOTAL_SEATS INT NOT NULL,
    AVAILABLE_SEATS INT NOT NULL,
    CONSTRAINT CK_WORKSHOP_TOTAL_SEATS CHECK (TOTAL_SEATS > 0),
    CONSTRAINT CK_WORKSHOP_AVAILABLE CHECK (AVAILABLE_SEATS >= 0 AND AVAILABLE_SEATS <= TOTAL_SEATS)
);

CREATE TABLE IF NOT EXISTS REGISTRATIONS (
    REG_ID BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
    STUDENT_NAME VARCHAR(150) NOT NULL,
    STUDENT_EMAIL VARCHAR(254) COLLATE utf8mb4_0900_ai_ci NOT NULL,
    WORKSHOP_ID BIGINT NOT NULL,
    REGISTERED_AT TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    CONSTRAINT FK_REGISTRATION_WORKSHOP FOREIGN KEY (WORKSHOP_ID)
        REFERENCES WORKSHOPS (WORKSHOP_ID),
    CONSTRAINT UQ_REGISTRATION_EMAIL_WORKSHOP UNIQUE (WORKSHOP_ID, STUDENT_EMAIL)
);

